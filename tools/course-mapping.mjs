/** Regenerates docs/COURSE_MAPPING.md from src/data/course.json (single source of truth). */
import { readFileSync, writeFileSync } from 'node:fs';
const c = JSON.parse(readFileSync(new URL('../src/data/course.json', import.meta.url)));
const esc = (s) => String(s).replace(/\|/g, '\\|');
const out = [];
out.push('# Course Traceability Matrix', '');
out.push(`Generated by \`node tools/course-mapping.mjs\` from \`src/data/course.json\` — the same data the in-game **Course Map** panel renders.`, '');
out.push(`> **Derived:** ${c.derivedFrom}`, '');
out.push(`Textbook: ${c.textbook || 'PMBOK Guide 8th Ed.'}`, '');
out.push('## 15-week matrix', '');
out.push('| Week | Topic | Panels | 3D mechanic | Missions | Quiz set | Tour beat | CLO | PMBOK 8 domain / focus area |', '|---|---|---|---|---|---|---|---|---|');
for (const w of c.weeks) {
  out.push(`| ${w.week} | ${esc(w.topic)} | ${w.panels.join(', ')} | ${esc(w.mechanic)} | ${w.missions.join(', ')} | ${w.quizSet} | ${w.tourBeat} | ${w.clo.join(', ')} | ${esc(w.domain)} |`);
}
out.push('', '## Learning outcomes (CLO) → features', '');
for (const k of c.clos) out.push(`* **${k.id}** — ${k.text}`, ...k.features.map((f) => `  * ${f}`));
out.push('', '## Course objectives → features', '');
for (const o of c.objectives) out.push(`* **${o.id}** (${o.clo.join(', ')}) — ${o.text}`, ...o.features.map((f) => `  * ${f}`));
out.push('', '## Check', '');
const empty = c.weeks.filter((w) => !w.panels.length || !w.missions.length || !w.quizSet || !w.tourBeat || !w.clo.length || !w.domain || !w.mechanic);
out.push(`* Rows: ${c.weeks.length} (15 required) — rows with an empty cell: ${empty.length}`);
out.push(`* Every CLO linked to ≥ 3 features: ${c.clos.every((k) => k.features.length >= 3) ? 'yes' : 'NO'}`);
out.push(`* Every objective linked to ≥ 3 features: ${c.objectives.every((o) => o.features.length >= 3) ? 'yes' : 'NO'}`);
writeFileSync(new URL('../docs/COURSE_MAPPING.md', import.meta.url), out.join('\n') + '\n');
console.log(out.slice(-3).join('\n'));
